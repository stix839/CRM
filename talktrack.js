'use strict';

// Default call script shown next to every lead. The owner can edit it in Settings.
// Format: "## Heading", "> spoken line", "1. numbered", "- bullet", "- [ ] checklist", "**bold**".
// [Owner], [Name], [Company], [town] and [observation] are filled in from the lead and the caller;
// any other [bracketed text] is shown as a blank to fill in on the call.
module.exports = `## Goal
Book a 20-minute appointment. Don't pitch pricing. Before dialing, check their Facebook/Instagram and note one thing (e.g., last post date).

## Opener
> "Hey [Owner], this is [Name] with M2. I'll be honest, this is a cold call. Can I have 30 seconds to tell you why I called, and you tell me if it's worth keeping going?"
> "We help contractors around [town] turn their own Facebook and Instagram into something that brings in work. Not ads. We come shoot your jobs and crew and run the page for you. I was looking at [Company]'s page and noticed [observation]. Quick question: where's most of your new work coming from right now?"

## Body
Ask 3–4, then listen. Write down his exact words.
1. Where's most of your new work coming from right now? (If word of mouth: "What happens in a slow month when referrals dry up?")
2. When someone gets referred to you, what's the first thing they do? (They look you up.)
3. Who's running your Facebook page right now? How often does it actually get done when you're slammed?
4. When you finish a job you're proud of, what happens to the pictures?
5. Are you paying for leads anywhere, like Angi or HomeAdvisor? How's that working?
6. Where do you want the business to be a year from now?

## Bridge
> "So if I heard you right, [his problem in his words]. That's exactly what we fix. We take social media completely off your plate and make sure that when people in town look you up, they see real work from your crew. No ads, no paying for leads."

## Close
> "Let's grab 20 minutes, at your shop or on a quick Zoom. I'll show you what we'd post for [Company] and what it would cost. If it doesn't make sense, no hard feelings. Is [Tuesday morning] or [Thursday afternoon] better?"
**If asked about price:** "Depends on how much content and how often. I'd rather show you real numbers than guess. That's what the 20 minutes is for."

## Before hanging up
- [ ] Confirm day, time and place.
- [ ] "Anyone else who should be in on this, like a partner or whoever handles the office?"
- [ ] Get best cell and email for the invite.
- [ ] "Can you text me a few pictures from recent jobs before we meet?"
`;
